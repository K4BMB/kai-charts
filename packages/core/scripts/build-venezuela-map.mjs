// Builds `packages/core/src/data/venezuela.ts` (the national map, 26 regions) from Natural Earth
// (public domain):
//   - ne_10m_admin_1_states_provinces  → the 23 states, Distrito Capital and Dependencias Federales
//   - ne_10m_admin_0_disputed_areas    → "West of Essequibo River" = the state of Guayana Esequiba
//
// Why a custom pipeline instead of a ready-made SVG: licensing (Wikimedia maps are CC-BY-SA, this
// library is MIT), shared borders (states are split into shared arcs before simplification, so
// neighbours never overlap or leave slivers) and a projection we control (`projectPoint()` in the
// core reuses the exact same parameters for markers and capitals). See `geo-lib.mjs`.
//
// Usage: node.exe packages/core/scripts/build-venezuela-map.mjs [--tolerance=0.6] [--width=800]
//        [--preview=C:/path/preview.svg]
// Downloads are cached in $KC_GEO_CACHE (default: ./.geo-cache, git-ignored).
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildRegionMap, centroid, loadJson, toPolygons, writePreview } from './geo-lib.mjs';
import { NATURAL_EARTH, venezuelaStates } from './venezuela-constants.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const args = Object.fromEntries(
  process.argv.slice(2).map((a) => {
    const [k, v] = a.replace(/^--/, '').split('=');
    return [k, v ?? 'true'];
  }),
);
const TOLERANCE = Number(args.tolerance ?? 0.6); // px at the chosen viewBox width
const WIDTH = Number(args.width ?? 800);
const cacheDir = process.env.KC_GEO_CACHE ?? join(here, '..', '.geo-cache');

const admin1 = await loadJson(cacheDir, NATURAL_EARTH.admin1.file, NATURAL_EARTH.admin1.url);
const disputed = await loadJson(cacheDir, NATURAL_EARTH.disputed.file, NATURAL_EARTH.disputed.url);
const states = venezuelaStates(admin1, disputed, { toPolygons, centroid });
console.log(
  `${states.length} regions (states, Distrito Capital, Dependencias Federales, Guayana Esequiba)`,
);

const map = buildRegionMap(states, { width: WIDTH, tolerance: TOLERANCE, padDeg: 0.15 });
const { stats } = map;
console.log(
  `${stats.rings} rings → ${stats.arcs} unique arcs (${stats.sharedArcs} shared borders reused)`,
);
console.log(
  `points ${stats.pointsBefore} → ${stats.pointsAfter} (tolerance ${TOLERANCE}px @ ${WIDTH}px)`,
);

const ts = `// AUTO-GENERATED by scripts/build-venezuela-map.mjs — do not edit by hand.
// Geometry: Natural Earth 10m (public domain). The 23 states, Distrito Capital, Dependencias
// Federales and the state of Guayana Esequiba (outline from the "disputed areas" layer, drawn as
// a regular state as Venezuelan law establishes).
// Projection: equirectangular, lon/lat → px with the parameters below (see projectPoint()).
// Simplified with shared borders (tolerance ${TOLERANCE}px at ${WIDTH}px wide).
import type { MapProjection, MapRegionGeometry } from './map-types.js';

export const VENEZUELA_VIEWBOX = { width: ${map.width}, height: ${map.height} } as const;

export const VENEZUELA_PROJECTION: MapProjection = {
  minLng: ${map.projection.minLng},
  maxLat: ${map.projection.maxLat},
  cosMid: ${map.projection.cosMid},
  scale: ${map.projection.scale},
};

/** The 26 regions of the Venezuelan map, sorted by id. */
export const VENEZUELA_STATES: readonly MapRegionGeometry[] = ${JSON.stringify(map.regions, null, 2)};
`;

const outFile = join(here, '..', 'src', 'data', 'venezuela.ts');
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, ts);
console.log(
  `wrote ${outFile} (${(Buffer.byteLength(ts) / 1024).toFixed(1)} KB), viewBox ${WIDTH}×${map.height}`,
);

if (args.preview) {
  writePreview(args.preview, map);
  console.log(`preview → ${args.preview}`);
}
